import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { cp, mkdir, rm, writeFile } from 'node:fs/promises'

const root = fileURLToPath(new URL('..', import.meta.url))
const packageRoot = join(root, 'packages', 'core')
await rm(join(packageRoot, 'icons'), { recursive: true, force: true })
await mkdir(packageRoot, { recursive: true })
await cp(join(root, 'assets', 'icons'), join(packageRoot, 'icons'), { recursive: true })

const catalog = JSON.parse(await Bun.file(join(root, 'assets', 'catalog.json')).text())
const aliases = JSON.parse(await Bun.file(join(root, 'assets', 'icon-aliases.json')).text())
const rootPackage = JSON.parse(await Bun.file(join(root, 'package.json')).text())
const ident = (s: string) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase()).replace(/[^A-Za-z0-9_$]/g, '')
const exportName = (s: string) => `${ident(s)}Original`
const categories = [...new Set(catalog.map((i: any) => i.category))].sort()

const sourcePath = (item: any, variant: string) => {
  for (const source of item.sources) {
    if (source.variants?.includes(variant)) {
      if (source.id === 'community') return `./icons/${item.category}/${item.name}/${variant}.svg`
      return `./icons/${item.category}/${item.name}/sources/${source.id}/${variant}.svg`
    }
  }
  return null
}

for (const category of categories) {
  const items = catalog.filter((i: any) => i.category === category)
  const lines = [`// Generated by bun run icons:package`, '']
  for (const item of items) {
    const base = ident(item.name)
    for (const variant of ['fill', 'outline', 'color', 'original', 'alternate']) {
      const p = sourcePath(item, variant)
      if (p) lines.push(`export const ${variant === 'original' ? exportName(item.name) : variant === 'alternate' ? `${base}Alternate` : `${base}${variant === 'fill' ? '' : variant[0].toUpperCase() + variant.slice(1)}`} = new URL(${JSON.stringify(p)}, import.meta.url).href`)
    }
  }
  for (const alias of aliases.filter((a: any) => a.category === category)) {
    const canonical = ident(alias.canonical)
    const name = ident(alias.name)
    lines.push(`export const ${name} = ${canonical}`)
    lines.push(`export const ${name}Outline = ${canonical}Outline`)
    lines.push(`export const ${name}Color = ${canonical}Color`)
  }
  await writeFile(join(packageRoot, `${category}.js`), lines.join('\n') + '\n')
}

const pkg = {
  name: 'islamic-icons', version: rootPackage.version, type: 'module', license: 'MIT',
  author: 'Rhein Sullivan | Vyagra Nexus™', files: ['*.js', 'icons', 'LICENSE', 'README.md'],
  exports: Object.fromEntries(categories.map(c => [`./${c}`, `./${c}.js`]))
}
await writeFile(join(packageRoot, 'package.json'), JSON.stringify(pkg, null, 2) + '\n')
await writeFile(join(packageRoot, 'README.md'), `# Islamic Icons\n\nFramework-agnostic Islamic SVG/WebP assets.\n\n\`\`\`js\nimport { allahCalligraphy, allahCalligraphyOutline, allahCalligraphyColor } from "islamic-icons/god"\n\`\`\`\n\nAuthor: Rhein Sullivan | Vyagra Nexus™\n`)
await writeFile(join(packageRoot, 'LICENSE'), await Bun.file(join(root, 'LICENSE')).text())
