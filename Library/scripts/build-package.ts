import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { cp, mkdir, rm, writeFile } from 'node:fs/promises'

const root = fileURLToPath(new URL('..', import.meta.url))
const packageRoot = join(root, 'packages', 'core')
await rm(join(packageRoot, 'icons'), { recursive: true, force: true })
await mkdir(packageRoot, { recursive: true })
await cp(join(root, 'assets', 'icons'), join(packageRoot, 'icons'), { recursive: true })

const catalog = JSON.parse(await Bun.file(join(root, 'assets', 'catalog.json')).text())
const aliases = JSON.parse(await Bun.file(join(root, 'assets', 'icon-aliases.json')).text())
const rootPackage = JSON.parse(await Bun.file(join(root, 'package.json')).text())
const ident = (s: string) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase()).replace(/[^A-Za-z0-9_$]/g, '')
const exportName = (s: string) => `${ident(s)}Original`
const categories = [...new Set(catalog.map((i: any) => i.category))].sort()

const sourcePath = (item: any, variant: string) => {
  for (const source of item.sources) {
    if (source.variants?.includes(variant)) {
      if (source.id === 'community') return `./icons/${item.category}/${item.name}/${variant}.svg`
      return `./icons/${item.category}/${item.name}/sources/${source.id}/${variant}.svg`
    }
  }
  return null
}

for (const category of categories) {
  const items = catalog.filter((i: any) => i.category === category)
  const lines: string[] = ['// Generated by bun run icons:package', '']
  const dtsLines: string[] = ['// Generated by bun run icons:package', '']
  for (const item of items) {
    const base = ident(item.name)
    for (const variant of ['fill', 'outline', 'color', 'original', 'alternate']) {
      const p = sourcePath(item, variant)
      if (!p) continue
      const name = variant === 'original' ? exportName(item.name) : variant === 'alternate' ? `${base}Alternate` : variant === 'fill' ? base : `${base}${variant[0].toUpperCase() + variant.slice(1)}`
      lines.push(`export const ${name} = new URL(${JSON.stringify(p)}, import.meta.url).href`)
      dtsLines.push(`export const ${name}: string`)
    }
  }
  for (const alias of aliases.filter((a: any) => a.category === category)) {
    const canonical = ident(alias.canonical)
    const name = ident(alias.name)
    lines.push(`export const ${name} = ${canonical}`)
    lines.push(`export const ${name}Outline = ${canonical}Outline`)
    lines.push(`export const ${name}Color = ${canonical}Color`)
    dtsLines.push(`export const ${name}: typeof ${canonical}`)
    dtsLines.push(`export const ${name}Outline: typeof ${canonical}Outline`)
    dtsLines.push(`export const ${name}Color: typeof ${canonical}Color`)
  }
  await writeFile(join(packageRoot, `${category}.js`), lines.join('\n') + '\n')
  await writeFile(join(packageRoot, `${category}.d.ts`), dtsLines.join('\n') + '\n')
}

await writeFile(join(packageRoot, 'index.js'), categories.map(c => `export * from "./${c}.js"`).join('\n') + '\n')
await writeFile(join(packageRoot, 'index.d.ts'), categories.map(c => `export * from "./${c}.d.ts"`).join('\n') + '\n')

const pkg = {
  name: 'islamic-icons',
  version: rootPackage.version,
  type: 'module',
  license: 'MIT',
  author: 'Islamic Icons Community | Vyagra Nexus™',
  description: 'Framework-agnostic Islamic SVG icon library for the modern web.',
  keywords: [
    'islamic',
    'icons',
    'svg',
    'islam',
    'mosque',
    'quran',
    'ramadan',
    'allahuakbar'
  ],
  main: './index.js',
  module: './index.js',
  types: './index.d.ts',
  exports: {
    '.': {
      import: './index.js',
      types: './index.d.ts'
    },
    ...Object.fromEntries(categories.map(c => [`./${c}`, { import: `./${c}.js`, types: `./${c}.d.ts` }])),
    './react': { import: './react/index.js', types: './react/index.d.ts' },
    './vue': { import: './vue/index.js', types: './vue/index.d.ts' },
    './svelte': { import: './svelte/index.js', types: './svelte/index.d.ts' },
    './astro': { import: './astro/index.js', types: './astro/index.d.ts' },
    './angular': { import: './angular/index.js', types: './angular/index.d.ts' },
    './solid': { import: './solid/index.jsx', types: './solid/index.d.ts' },
    './preact': { import: './preact/index.js', types: './preact/index.d.ts' },
    './react-native': { import: './react-native/index.js', types: './react-native/index.d.ts' },
    './static': { import: './static/index.js', types: './static/index.d.ts' }
  },
  files: ['*.js', '*.d.ts', 'icons', 'react', 'vue', 'svelte', 'astro', 'angular', 'solid', 'preact', 'react-native', 'static', 'LICENSE', 'README.md'],
  sideEffects: false
}
await writeFile(join(packageRoot, 'package.json'), JSON.stringify(pkg, null, 2) + '\n')
const existingReadme = await Bun.file(join(packageRoot, 'README.md')).exists().catch(() => false)
if (!existingReadme) await writeFile(join(packageRoot, 'README.md'), `# Islamic Icons\n\nFramework-agnostic Islamic SVG/WebP assets.\n\n\`\`\`js\nimport { allahCalligraphy, allahCalligraphyOutline, allahCalligraphyColor } from "islamic-icons/god"\n\`\`\`\n\nAuthor: Islamic Icons Community | Vyagra Nexus™\n`)
await writeFile(join(packageRoot, 'LICENSE'), await Bun.file(join(root, 'LICENSE')).text())
